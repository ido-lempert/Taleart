// Measures the built Web SDK for the docs' performance page (apps/docs/src/app/pages/web-performance.ts)
// and writes the numbers to apps/docs/src/app/pages/sdk-budget.generated.ts.
// The ESM size is every ES chunk together (readChunks, as check-size.mjs judges it); the UMD size is the
// .cjs bundle. Both are gzipped at levels 9 and 6 and the larger is kept, as the budget judges them.
// Run through `nx run web-sdk:measure-budget`, which builds first. The argument is the build folder.
import { mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { BUNDLE_LIMIT_BYTES, gzipped, readChunks } from './size-budget.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../../..');
const arg = resolve(process.argv[2] ?? 'dist/libs/web-sdk');
const dir = statSync(arg).isDirectory() ? arg : dirname(arg);
const OUTPUT = join(root, 'apps/docs/src/app/pages/sdk-budget.generated.ts');

const toKb = (bytes) => Number((bytes / 1024).toFixed(2));
const larger = (code) => Math.max(gzipped(code, 9), gzipped(code, 6));

const esmBytes = readChunks(dir).reduce((sum, chunk) => sum + chunk.gzipped, 0);
const umdBytes = larger(readFileSync(join(dir, 'index.umd.cjs'), 'utf8'));
const esmGzipKb = toKb(esmBytes);
const umdGzipKb = toKb(umdBytes);
const budgetKb = BUNDLE_LIMIT_BYTES / 1024;

const generated = `// Generated by libs/web-sdk/scripts/measure-budget.mjs (nx run web-sdk:measure-budget). Do not edit.
export const SDK_BUDGET = {
  budgetKb: ${budgetKb},
  esmGzipKb: ${esmGzipKb.toFixed(2)},
  umdGzipKb: ${umdGzipKb.toFixed(2)},
  measuredAt: '${new Date().toISOString()}',
} as const;
`;

mkdirSync(dirname(OUTPUT), { recursive: true });
writeFileSync(OUTPUT, generated);
console.log(`Web SDK budget in ${dir}: ESM ${esmGzipKb.toFixed(2)} KB, UMD ${umdGzipKb.toFixed(2)} KB gzipped (budget ${budgetKb} KB)`);
console.log(`Wrote ${OUTPUT}`);
